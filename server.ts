// Verify Final Terms Comparison Endpoint
app.post('/api/verify-final-terms', (req, res) => {
  try {
    const { explainedFacts, proposedFacts, sessionId, clientAcknowledgedChanges } = req.body;

    if (!explainedFacts || !proposedFacts) {
      return res.status(400).json({
        error: 'Both explainedFacts and proposedFacts are required for comparison',
        isMatch: false,
        isUnparseable: true
      });
    }

    // Check numerical differences
    const sanctionedMatches = explainedFacts.sanctionedAmountPaise === proposedFacts.sanctionedAmountPaise;
    const upfrontMatches = explainedFacts.upfrontFeePaise === proposedFacts.upfrontFeePaise;
    const netMatches = explainedFacts.netDisbursementPaise === proposedFacts.netDisbursementPaise;
    const repaymentMatches = explainedFacts.totalScheduledRepaymentPaise === proposedFacts.totalScheduledRepaymentPaise;
    const lenderMatches = (explainedFacts.lenderName || '').trim().toLowerCase() === (proposedFacts.lenderName || '').trim().toLowerCase();

    const isMatch = sanctionedMatches && upfrontMatches && netMatches && repaymentMatches && lenderMatches;
    const repaymentDiffPaise = proposedFacts.totalScheduledRepaymentPaise - explainedFacts.totalScheduledRepaymentPaise;

    // If there is a material change and client did NOT explicitly re-acknowledge
    if (!isMatch && !clientAcknowledgedChanges) {
      return res.status(409).json({
        isMatch: false,
        error: 'MATERIAL_TERMS_CHANGED',
        message: 'The final contract terms differ from the explained version. Borrower re-acknowledgement required.',
        repaymentDiffPaise,
        repaymentDiffRupees: repaymentDiffPaise / 100,
        sanctionedMatches,
        upfrontMatches,
        netMatches,
        repaymentMatches
      });
    }

    res.json({
      isMatch,
      status: 'verified',
      repaymentDiffPaise,
      repaymentDiffRupees: repaymentDiffPaise / 100,
      timestamp: new Date().toISOString()
    });
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

