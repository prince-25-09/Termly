// Transcribe Audio Endpoint (Gemini gemini-3.5-transcribe)
app.post('/api/transcribe-audio', async (req, res) => {
  try {
    const { audioBase64, mimeType = 'audio/webm', language = 'hi' } = req.body;

    if (!audioBase64) {
      return res.status(400).json({ error: 'Audio data is required' });
    }

    const ai = getGemini();

    if (!ai) {
      return res.status(503).json({
        error: 'Gemini API not configured on server',
        fallback: true,
        transcript: ''
      });
    }

    // Clean base64 header if present (e.g. data:audio/webm;base64,...)
    const cleanBase64 = audioBase64.replace(/^data:[^;]+;base64,/, '');

    const audioPart = {
      inlineData: {
        mimeType: mimeType.includes('mp4') ? 'audio/mp4' : mimeType.includes('wav') ? 'audio/wav' : 'audio/webm',
        data: cleanBase64
      }
    };

    const promptText = `Transcribe the borrower's spoken response accurately.
The borrower may speak in Hindi, Indian English, or mixed Hinglish.
Do NOT translate the response. Transcribe verbatim in the language spoken (Devanagari for Hindi words, Roman script for Hinglish/English).
Output ONLY the transcription without prefixes or conversational commentary.`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.5-transcribe',
      contents: {
        parts: [
          audioPart,
          { text: promptText }
        ]
      }
    });

    const transcript = (response.text || '').trim();

    res.json({
      transcript,
      confidence: transcript.length > 5 ? 'high' : 'medium',
      language
    });
  } catch (error: any) {
    console.error('Audio transcription error:', error);
    res.status(500).json({
      error: error.message || 'Failed to transcribe audio',
      fallback: true
    });
  }
});

// Synthesize Speech Endpoint (Gemini gemini-3.1-flash-tts-preview)
app.post('/api/synthesize-speech', async (req, res) => {
  try {
    const { text, language = 'en' } = req.body;

    if (!text) {
      return res.status(400).json({ error: 'Text is required for speech synthesis' });
    }

    const ai = getGemini();

    if (!ai) {
      return res.status(503).json({
        error: 'Gemini TTS unavailable, fallback to browser synthesis',
        fallback: true
      });
    }

    const voiceName = language === 'hi' ? 'Kore' : 'Puck';
    const cleanText = text.replace(/[*_#`]/g, '').trim();

    const response = await ai.models.generateContent({
      model: 'gemini-3.1-flash-tts-preview',
      contents: [{
        parts: [{
          text: `Read in a warm, patient, clear, and reassuring tone for a first-time borrower: ${cleanText}`
        }]
      }],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName }
          }
        }
      }
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;

    if (base64Audio) {
      res.json({
        audioBase64: base64Audio,
        mimeType: 'audio/wav',
        voice: voiceName
      });
    } else {
      res.status(500).json({
        error: 'No audio generated by TTS model',
        fallback: true
      });
    }
  } catch (err: any) {
    console.warn('Gemini TTS notice, falling back to browser speech:', err?.message);
    res.status(500).json({
      error: err.message || 'TTS generation failed',
      fallback: true
    });
  }
});

// Evaluate Borrower Comprehension Endpoint (Gemini gemini-3.7-flash + Rule Engine)
app.post('/api/evaluate-comprehension', async (req, res) => {
  try {
    const { questionId, concept, userTranscript, language = 'en', offerFacts, attemptCount = 1 } = req.body;

    if (!userTranscript || typeof userTranscript !== 'string') {
      return res.status(400).json({ error: 'Valid user transcript is required' });
    }

    const ai = getGemini();
    const evaluation = await evaluateComprehension(ai, {
      questionId,
      concept: concept || questionId,
      userTranscript: userTranscript.trim(),
      language: language as 'en' | 'hi',
      offerFacts,
      attemptCount: Number(attemptCount) || 1
    });

    res.json(evaluation);
  } catch (error: any) {
    console.error('Comprehension evaluation error:', error);
    res.status(500).json({
      error: error.message || 'Failed to evaluate comprehension',
      status: 'unable_to_assess',
      evidence: 'Server evaluation temporary glitch.'
    });
  }
});

